"""
Design System Exporter
Generates DESIGN_SYSTEM.md and tokens.json (W3C / Tailwind format).
"""

import os
import json
from typing import Dict, Any, List

def generate_design_system_files(run_id: str, tokens: Dict[str, Any], output_dir: str) -> Dict[str, str]:
    """
    Creates DESIGN_SYSTEM.md and tokens.json in output_dir/exports/.
    """
    exports_dir = os.path.join(output_dir, "exports")
    os.makedirs(exports_dir, exist_ok=True)

    md_path = os.path.join(exports_dir, "DESIGN_SYSTEM.md")
    json_path = os.path.join(exports_dir, "tokens.json")

    colors = tokens.get("colors", [])
    typography = tokens.get("typography", {})
    radii = tokens.get("radii", [])
    shadows = tokens.get("shadows", [])

    # 1. Generate Markdown Report
    md_lines = [
        "# Design System Audit & Token Report",
        "",
        f"> Automatically generated by Visual Intelligence Studio for run `{run_id}`.",
        "",
        "---",
        "",
        "## 🎨 Color Palette",
        "",
        "| Role | Hex | Preview | Frequency |",
        "| :--- | :--- | :--- | :--- |",
    ]

    for c in colors:
        hex_val = c.get("hex", "#000000")
        cat = c.get("category", "color").capitalize()
        count = c.get("count", 1)
        # Markdown color swatch representation
        swatch = f"`{hex_val}`"
        md_lines.append(f"| {cat} | `{hex_val}` | {swatch} | {count} elements |")

    md_lines.extend([
        "",
        "---",
        "",
        "## ✍️ Typography Scale",
        "",
        "| Element | Font Family | Size | Weight | Line Height |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ])

    for tag, t in typography.items():
        md_lines.append(
            f"| `{tag.upper()}` | {t.get('fontFamily', '-')} | `{t.get('fontSize', '-')}` | {t.get('fontWeight', '-')} | `{t.get('lineHeight', '-')}` |"
        )

    md_lines.extend([
        "",
        "---",
        "",
        "## 📐 Border Radii",
        "",
    ])

    if radii:
        for r in radii:
            md_lines.append(f"- `{r}`")
    else:
        md_lines.append("- No significant border-radius values detected.")

    md_lines.extend([
        "",
        "---",
        "",
        "## 🌫️ Box Shadows",
        "",
    ])

    if shadows:
        for s in shadows:
            md_lines.append(f"- `{s}`")
    else:
        md_lines.append("- No significant box-shadows detected.")

    with open(md_path, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))

    # 2. Generate tokens.json (W3C standard format)
    w3c_tokens = {
        "$schema": "https://design-tokens.github.io/community-group/format/",
        "color": {
            f"color-{i+1}": {
                "$value": c["hex"],
                "$type": "color",
                "$description": f"Extracted {c.get('category')} token (used {c.get('count')} times)"
            }
            for i, c in enumerate(colors)
        },
        "typography": {
            tag: {
                "fontFamily": {"$value": t.get("fontFamily"), "$type": "fontFamily"},
                "fontSize": {"$value": t.get("fontSize"), "$type": "dimension"},
                "fontWeight": {"$value": t.get("fontWeight"), "$type": "fontWeight"},
            }
            for tag, t in typography.items()
        },
        "borderRadius": {
            f"radius-{i+1}": {"$value": r, "$type": "dimension"}
            for i, r in enumerate(radii)
        }
    }

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(w3c_tokens, f, indent=2)

    return {"md_path": md_path, "json_path": json_path}
