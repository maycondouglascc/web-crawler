"""
AI Agent Context Pack Exporter
Generates CONTEXT.md / llms.txt designed for AI coding agents (Antigravity, Cursor, Claude Code)
to accurately rebuild or redesign the web application.
"""

import os
from typing import Dict, Any, List

def generate_context_pack(
    run_id: str,
    base_url: str,
    routes: List[Dict[str, Any]],
    sections: List[Dict[str, Any]],
    components: List[Dict[str, Any]],
    tokens: Dict[str, Any],
    output_dir: str
) -> str:
    """
    Generates CONTEXT.md in output_dir/exports/.
    """
    exports_dir = os.path.join(output_dir, "exports")
    os.makedirs(exports_dir, exist_ok=True)
    filepath = os.path.join(exports_dir, "CONTEXT.md")

    lines = [
        f"# AI Coding Agent Context Pack: {base_url}",
        "",
        f"> Generated by Visual Intelligence Studio (Run: `{run_id}`).",
        "> Use this file to provide complete visual and structural context to AI coding agents.",
        "",
        "---",
        "",
        "## 🗺️ Route Architecture",
        "",
        f"Target Base URL: `{base_url}`",
        f"Total Discovered Routes: `{len(routes)}`",
        "",
        "| Route Path | Pattern | Sample URL |",
        "| :--- | :--- | :--- |",
    ]

    for r in routes:
        lines.append(f"| `{r.get('path')}` | `{r.get('pattern')}` | `{r.get('full_url')}` |")

    lines.extend([
        "",
        "---",
        "",
        "## 🧩 Sliced Semantic Page Sections",
        "",
        f"Total Sliced Sections: `{len(sections)}`",
        "",
        "| Section Type | Route | Viewport | Screenshot Asset |",
        "| :--- | :--- | :--- | :--- |",
    ])

    for s in sections[:30]:
        filename = os.path.basename(s.get("file_path", ""))
        lines.append(f"| `{s.get('section_category', 'section')}` | `{s.get('route_path')}` | {s.get('viewport_label')} | `{filename}` |")

    lines.extend([
        "",
        "---",
        "",
        "## 📦 Harvested UI Component Inventory",
        "",
        f"Total Unique Component Variants: `{len(components)}`",
        "",
        "| Category | Fingerprint | Frequency | Preview Asset | Key CSS |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ])

    for c in components[:25]:
        fp = c.get("fingerprint", "")
        cat = c.get("category", "")
        count = c.get("instances_count", 1)
        prev = os.path.basename(c.get("preview_path", ""))
        styles = c.get("computed_styles", {})
        style_summary = f"bg: {styles.get('backgroundColor', '-')} | text: {styles.get('color', '-')} | radius: {styles.get('borderRadius', '-')}"
        lines.append(f"| `{cat}` | `fp:{fp}` | Used {count}x | `{prev}` | {style_summary} |")

    # Design tokens summary
    lines.extend([
        "",
        "---",
        "",
        "## 🎨 Extracted Design Tokens Summary",
        "",
        "### Key Colors:",
    ])

    for col in tokens.get("colors", [])[:8]:
        lines.append(f"- **{col.get('category', 'color').capitalize()}**: `{col.get('hex')}` (Used {col.get('count')} times)")

    lines.extend([
        "",
        "---",
        "",
        "## 🤖 AI Coding Agent Prompt Recipes",
        "",
        "### Recipe 1: Rebuild Page with Exact Visual Fidelity",
        "```markdown",
        f"You are rebuilding the web application at {base_url}.",
        "Refer to CONTEXT.md for the complete route structure, design tokens, and component inventory.",
        "- Extract color hex codes and font families directly from the Design Tokens section.",
        "- Recreate each page layout section by section following the Sliced Sections table.",
        "- Use the corresponding screenshot PNGs in the /sections folder as the visual source of truth.",
        "```",
        "",
        "### Recipe 2: Design System Component Implementation",
        "```markdown",
        "Build reusable React / Tailwind CSS components for all harvested UI components in CONTEXT.md.",
        "- Match the extracted background color, font size, border-radius, and padding specified in the inventory.",
        "```"
    ])

    with open(filepath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    # Also save as llms.txt standard
    llms_txt_path = os.path.join(exports_dir, "llms.txt")
    with open(llms_txt_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    return filepath
